type FilterOperator = "contains" | "equals" | "starts_with" | "gt" | "lt" | "is_null" | "not_null"

function formatCellValue(val: any): string {
  if (val === null || val === undefined) return "NULL"
  if (typeof val === "boolean") return val ? "true" : "false"
  if (typeof val === "object") {
    try {
      return JSON.stringify(val)
    } catch {
      return String(val)
    }
  }
  return String(val)
}

function coerceColumnValue(col: TableColumnSchema, rawVal: any): any {
  if (rawVal === null) return null
  if (rawVal === "" || rawVal === undefined) {
    if (col.required && !col.autoGenerated) {
      throw new Error(`Column "${col.name}" cannot be empty.`)
    }
    return null
  }

  if (col.type === "boolean") {
    return rawVal === true || rawVal === "true"
  }
  if (col.type === "numeric") {
    const num = Number(rawVal)
    if (Number.isNaN(num)) {
      throw new Error(`Column "${col.name}" must be a valid number.`)
    }
    return num
  }
  if (col.type === "int4" || col.type === "int8") {
    const intVal = parseInt(String(rawVal), 10)
    if (Number.isNaN(intVal)) {
      throw new Error(`Column "${col.name}" must be a valid integer.`)
    }
    return intVal
  }
  if (col.type === "jsonb") {
    try {
      return typeof rawVal === "string" ? JSON.parse(rawVal) : rawVal
    } catch {
      throw new Error(`Column "${col.name}" must contain valid JSON.`)
    }
  }
  return String(rawVal).trim()
}

